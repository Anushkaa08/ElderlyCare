
import { useState } from "react";
import { ArrowLeft, History, Activity } from "lucide-react";

function HealthHistory({ history = [], onBack }) {
  const [filter, setFilter] = useState("all");

  const filteredHistory =
    filter === "all"
      ? history
      : history.filter((item) => {
          const date = new Date(item.timestamp || item.time || item.date);
          const now = new Date();

          if (filter === "today") {
            return date.toDateString() === now.toDateString();
          }

          if (filter === "week") {
            return now - date <= 7 * 24 * 60 * 60 * 1000;
          }

          return true;
        });

  return (
    <div className="min-h-screen bg-slate-50 p-5 md:p-8">
      <div className="mb-6 flex items-center gap-3">
        <button
          onClick={onBack}
          className="rounded-xl border bg-white p-3 hover:bg-slate-100"
        >
          <ArrowLeft size={20} />
        </button>

        <div>
          <h2 className="text-2xl font-bold text-slate-800">
            Health History
          </h2>
          <p className="text-sm text-slate-500">
            View previous simulated health readings
          </p>
        </div>
      </div>

      <div className="mb-6 rounded-2xl border border-blue-200 bg-blue-50 p-4">
        <p className="font-medium text-blue-800">
          <Activity className="mr-2 inline" size={18} />
          Simulation Data
        </p>
        <p className="mt-1 text-sm text-blue-700">
          These readings are generated by the software simulation
          and are not real medical measurements.
        </p>
      </div>

      <div className="rounded-2xl border bg-white p-5 shadow-sm">
        <div className="mb-5 flex flex-wrap items-center justify-between gap-4">
          <div className="flex items-center gap-2">
            <History size={22} className="text-teal-600" />
            <h3 className="text-lg font-bold text-slate-800">
              Reading Records
            </h3>
          </div>

          <select
            value={filter}
            onChange={(e) => setFilter(e.target.value)}
            className="rounded-xl border border-slate-300 px-4 py-2"
          >
            <option value="all">All Records</option>
            <option value="today">Today</option>
            <option value="week">Last 7 Days</option>
          </select>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full min-w-[850px] text-left">
            <thead>
              <tr className="border-b bg-slate-50 text-sm text-slate-600">
                <th className="px-4 py-3">Time</th>
                <th className="px-4 py-3">Heart Rate</th>
                <th className="px-4 py-3">Oxygen</th>
                <th className="px-4 py-3">Temperature</th>
                <th className="px-4 py-3">Blood Pressure</th>
              </tr>
            </thead>

            <tbody>
              {filteredHistory.length > 0 ? (
                filteredHistory.map((item, index) => (
                  <tr
                    key={index}
                    className="border-b hover:bg-slate-50"
                  >
                    <td className="px-4 py-3 text-sm">
                      {item.timestamp || item.time || item.date
                        ? new Date(
                            item.timestamp || item.time || item.date
                          ).toLocaleString()
                        : "Unknown"}
                    </td>

                    <td className="px-4 py-3">
                      {item.heartRate ?? item.hr ?? "--"} bpm
                    </td>

                    <td className="px-4 py-3">
                      {item.oxygen ?? item.spo2 ?? "--"}%
                    </td>

                    <td className="px-4 py-3">
                      {item.temperature ?? item.temp ?? "--"} °C
                    </td>

                    <td className="px-4 py-3">
                      {item.bloodPressure ??
                        item.bp ??
                        (item.systolic && item.diastolic
                          ? `${item.systolic}/${item.diastolic}`
                          : "--")}
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td
                    colSpan="5"
                    className="py-12 text-center text-slate-500"
                  >
                    No records available for this filter.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        <div className="mt-4 text-sm text-slate-500">
          Total records: {filteredHistory.length}
        </div>
      </div>
    </div>
  );
}

export default HealthHistory;
